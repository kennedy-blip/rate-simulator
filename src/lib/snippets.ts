export function getSnippet(algo: AlgorithmId, lang: LangId, cfg: LimiterConfig): string {
  if (lang === "express") return EXPRESS[algo](cfg);
  if (lang === "fastapi") return FASTAPI[algo](cfg);
  return NEXTJS[algo](cfg);
}

export function exportConfig(
  algo: AlgorithmId,
  cfg: LimiterConfig,
  extra: Record<string, unknown>,
): string {
  return JSON.stringify(
    {
      name: "RatePulse configuration",
      generatedAt: new Date().toISOString(),
      algorithm: { id: algo, name: ALGO_NAME[algo] },
      parameters: {
        capacity: cfg.capacity,
        refillRatePerSecond: cfg.refillRate,
        requestRatePerSecond: cfg.requestRate,
        windowSeconds: cfg.windowSeconds,
      },
      expected: extra,
      headersEmitted: [
        "X-RateLimit-Limit",
        "X-RateLimit-Remaining",
        "X-RateLimit-Reset",
        "X-RateLimit-Policy",
        "Retry-After",
      ],
    },
    null,
    2,
  );
}
